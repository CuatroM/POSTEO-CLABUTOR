LAT0 = math.cos(math.radians(38))
LON_MIN, LON_MAX, LAT_MAX, LAT_MIN = -74.0, -53.2, -21.5, -55.3


def proyectar(lon, lat, ancho):
    escala = ancho / ((LON_MAX - LON_MIN) * LAT0)
    return ((lon - LON_MIN) * LAT0 * escala, (LAT_MAX - lat) * escala)


def tamano(ancho):
    return ancho, proyectar(LON_MIN, LAT_MIN, ancho)[1]


def path(ancho):
    partes = []
    for poli in (CONTINENTAL, TIERRA_DEL_FUEGO, MALVINAS_O, MALVINAS_E):
        pts = [proyectar(lon, lat, ancho) for lon, lat in poli]
        partes.append("M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z")
    return " ".join(partes)
